#!/usr/bin/env bash
# factory-link.sh — put a factory's next lane on the PATH as <tool>-next.
#
# The bare command (<tool>) runs the live lane or an installed release. A
# release candidate waits in next, and nobody used it before a promote: trying
# it meant typing the lane's path. <tool>-next runs the next lane, so the owner
# and agents use it for real work first. Side by side, never a switch: which
# lane runs is always in the command's name.
#
# factory.json:
#   "cli": {
#     "name": "sitescope",          the command; the wrapper is <name>-next
#     "entry": "src/cli.ts",        the entry point inside a lane
#     "run": "bun",                 optional: the program that runs the entry
#     "nextChangesData": "..."      optional: what the next lane migrates in
#   }                               data it shares with live (config, a db)
#
# Hard rule (owner, 2026-09-30): every command answers --version with exit 0
# and a version number, in the live lane and in next. --check runs both.
#
# Lanes share the user's data. A next lane that rewrites it rewrites it for
# live too, so nextChangesData makes the wrapper say so on every run.
#
# Usage:
#   factory-link.sh --factory PATH           write or refresh <name>-next
#   factory-link.sh --factory PATH --check   report only (factory-doctor reads it)
# Env: FACTORY_BIN_DIR (default ~/.local/bin).
set -euo pipefail

FACTORY=""; CHECK=false
while [ "$#" -gt 0 ]; do
	case "$1" in
		--factory) FACTORY="$2"; shift 2 ;;
		--check) CHECK=true; shift ;;
		-h|--help) sed -n '2,25p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
		*) echo "error: unknown option: $1" >&2; exit 2 ;;
	esac
done
FACTORY="$(cd "${FACTORY:-$PWD}" && pwd)"
BIN_DIR="${FACTORY_BIN_DIR:-$HOME/.local/bin}"
PROFILE_BIN="$(dirname "$(realpath "${BASH_SOURCE[0]}")")/factory-profile.py"
PROFILE_JSON="$(python3 "$PROFILE_BIN" "$FACTORY")" || exit 1

LOADER="$(bash "$(dirname "$(realpath "${BASH_SOURCE[0]}")")/factory-paths.sh" loader)"
python3 - "$FACTORY" "$PROFILE_JSON" "$BIN_DIR" "$CHECK" "$LOADER" <<'PY'
import json, os, re, subprocess, sys
from pathlib import Path
root, profile, bin_dir, check, loader = Path(sys.argv[1]), json.loads(sys.argv[2]), Path(sys.argv[3]), sys.argv[4] == "true", sys.argv[5]
MARK = "# generated by factory-link.sh"
cli = json.loads((root / "factory.json").read_text()).get("cli")
if not cli:
    sys.exit(0)  # no command to put on the PATH (an app, a library)
name, entry, run = cli.get("name", ""), cli.get("entry", ""), cli.get("run", "")
if not name or not entry:
    print("FAIL cli needs name and entry"); sys.exit(1)
nxt = profile["lanes"].get("next")
if not nxt:
    print("FAIL cli is set but the factory has no next lane"); sys.exit(1)
lane = Path(os.path.expanduser(nxt))
target = lane / entry
fails, notes, infos = [], [], []  # infos never count, not even in --strict
if not target.is_file():
    fails.append(f"{name}-next: {entry} is missing in the next lane ({target})")
pkg = lane / "package.json"
if pkg.is_file():
    try:
        deps = json.loads(pkg.read_text()).get("dependencies") or {}
    except ValueError:
        deps = {}
    if deps and not (lane / "node_modules").is_dir():
        notes.append(f"{name}-next: the next lane has no node_modules; install its dependencies there")

warn = cli.get("nextChangesData", "")
lines = ["#!/usr/bin/env bash",
         f"{MARK} for {root.name}; do not edit.",
         f"# {name}-next runs the next lane ({lane}); {name} stays on live.",
         "# The central paths file (factory-paths.sh), as the shell loads it:"]
lines += loader.splitlines()
if warn:
    msg = f"{name}-next: this lane changes data live shares: {warn}".replace("'", "")
    lines.append(f"echo '{msg}' >&2")
cmd = f'exec {run} "{target}" "$@"' if run else f'exec "{target}" "$@"'
lines.append(cmd)
want = "\n".join(lines) + "\n"
wrapper = bin_dir / f"{name}-next"

if check:
    # Hard rule: every command answers --version (exit 0, a version number),
    # so <tool> and <tool>-next can always be told apart.
    # The candidate is what the rule holds strictly: a live lane without
    # --version is only a note while next has it, because promoting next is
    # how live gets it (a fail there blocked the very pipeline that fixes it).
    version_ok = {}
    for key in ("next", "live"):
        lp = profile["lanes"].get(key)
        if not lp:
            continue
        ep = Path(os.path.expanduser(lp)) / entry
        if not ep.is_file():
            if key == "live":
                fails.append(f"{name}: {entry} is missing in the live lane ({ep})")
            continue
        try:
            r = subprocess.run(([run] if run else []) + [str(ep), "--version"], capture_output=True,
                               text=True, timeout=30, stdin=subprocess.DEVNULL)
            out, rc = (r.stdout + r.stderr).strip(), r.returncode
        except (OSError, subprocess.TimeoutExpired) as e:
            out, rc = str(e), -1
        version_ok[key] = rc == 0 and bool(re.search(r"\d+\.\d+\.\d+", out))
        if not version_ok[key]:
            first = out.splitlines()[0][:80] if out else "no output"
            msg = f"{name} ({key} lane): --version must exit 0 and print a version; got exit {rc}: {first}"
            if key == "live" and version_ok.get("next"):
                infos.append(msg + " (next has it: promoting next fixes live)")
            else:
                fails.append(msg)
    if not wrapper.exists():
        notes.append(f"{name}-next is not on the PATH yet; run factory-link.sh --factory {root}")
    elif MARK not in wrapper.read_text(errors="ignore"):
        fails.append(f"{wrapper} exists and was not made by factory-link.sh")
    elif wrapper.read_text() != want:
        notes.append(f"{name}-next is out of date with factory.json; run factory-link.sh --factory {root}")
    for f in fails: print(f"FAIL {f}")
    for n in notes: print(f"NOTE {n}")
    for i in infos: print(f"INFO {i}")
    sys.exit(1 if fails else 0)

for f in fails: print(f"FAIL {f}")
if fails:
    sys.exit(1)
if wrapper.exists() and MARK not in wrapper.read_text(errors="ignore"):
    print(f"FAIL {wrapper} exists and was not made by factory-link.sh; not overwriting it"); sys.exit(1)
bin_dir.mkdir(parents=True, exist_ok=True)
tmp = wrapper.with_suffix(".tmp")
tmp.write_text(want); tmp.chmod(0o755); tmp.replace(wrapper)
for n in notes: print(f"NOTE {n}")
print(f"linked {wrapper} -> {target}")
PY
